    /**
     * Returns true if automation is allowed to insert the given stack (ignoring
     * stack size) into the given slot.
     */
    @Override
    public boolean isItemValidForSlot(int slotID, ItemStack itemStack)
    {
        if (itemStack == null) return false;
        if(slotID == 0) return ItemElectricBase.isElectricItem(itemStack.getItem());
        if(slotID == 1) return itemStack.getItem() == new ItemStack(Items.water_bucket).getItem();
        if(slotID == 2) return itemStack.getItem() == new ItemStack(Items.dye, 1, 15).getItem();
        if(slotID == 3) return itemStack.getItem() == new ItemStack(Items.wheat_seeds).getItem();
        if(slotID == 4) 
        {
        		return true;
        }
       /* for (ItemStack i : blocks)
		{
        	if(slotID == 4) return itemStack == i;
		}*/
    	return false;
    }


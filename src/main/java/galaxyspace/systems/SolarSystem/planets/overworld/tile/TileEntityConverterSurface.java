    public TileEntityConverterSurface()
    {
        this(1);
    }

    /*
     * @param tier: 1 = Electric Furnace  2 = Electric Arc Furnace
     */
    public TileEntityConverterSurface(int tier)
    {
        this.initialised = true;
        if (tier == 1)
        {
            this.storage.setMaxExtract(ConfigManagerCore.hardMode ? 60 : 45);
            return;
        }

        this.setTier2();
    }
    
    private void setTier2()
    {
        this.storage.setCapacity(25000);
        this.storage.setMaxExtract(ConfigManagerCore.hardMode ? 90 : 60);
        this.processTimeRequired = 100;
        this.setTierGC(2);   	
    }

    public int getScaledWaterLevel(int i)
    {
         return this.waterTank.getFluidAmount() * i / this.waterTank.getCapacity();
    }
    
    @Override
    public void updateEntity()
    {
        if (!this.initialised )
        {
            int metadata = this.getBlockMetadata();
            //for version update compatibility
            Block b = this.worldObj.getBlock(this.xCoord, this.yCoord, this.zCoord);
            if (b == GCBlocks.machineBase)
            {
                this.worldObj.setBlock(this.xCoord, this.yCoord, this.zCoord, GCBlocks.machineTiered, 4, 2);
            }
            else if (metadata >= 8)
            {
            	this.setTier2();
            }
            this.initialised = true;
        }

        super.updateEntity();

        if (!this.worldObj.isRemote)
        {

                if (this.containingItems[1] != null)
                {
                	 FluidStack liquid = FluidContainerRegistry.getFluidForFilledItem(this.containingItems[1]);
                		
 	                if (liquid != null)
 	                {
 	                	boolean isWater = FluidRegistry.getFluidName(liquid).startsWith("water");
 		
 		                if (isWater)
 		                {
 		                    if (this.waterTank.getFluid() == null || this.waterTank.getFluid().amount + liquid.amount <= this.waterTank.getCapacity())
 		                    {
 		                        this.waterTank.fill(new FluidStack(FluidRegistry.WATER, liquid.amount), true);
 		
 		                        if (FluidContainerRegistry.isBucket(this.containingItems[1]) && FluidContainerRegistry.isFilledContainer(this.containingItems[1]))
 		                        {
 		                            final int amount = this.containingItems[1].stackSize;
 		                            if (amount > 1) this.waterTank.fill(new FluidStack(FluidRegistry.WATER, (amount - 1) * FluidContainerRegistry.BUCKET_VOLUME), true);
 		                            this.containingItems[1] = new ItemStack(Items.bucket, amount);
 		                        }
 		                        else
 		                        {
 		                            this.containingItems[1].stackSize--;
 		
 		                            if (this.containingItems[1].stackSize == 0)
 		                            {
 		                                this.containingItems[1] = null;
 		                            }
 		                        }
 		                    }
 		                }
 	                }
                }
                
            if (this.canProcess())
            {
               if (this.hasEnoughEnergyToRun)
                {
                    //50% extra speed boost for Tier 2 machine if powered by Tier 2 power
                    if (this.tierGC == 2) this.processTimeRequired = 200 / (1 + this.poweredByTierGC);

                    if (this.processTicks == 0)
                    {
                        this.processTicks = this.processTimeRequired;
                    }
                    else
                    {
                        if (--this.processTicks <= 0)
                        {
                            this.smeltItem();
                            this.processTicks = this.canProcess() ? this.processTimeRequired : 0;
                        }
                    }
                }
                else if (this.processTicks > 0 && this.processTicks < this.processTimeRequired)
                {
                    //Apply a "cooling down" process if the electric furnace runs out of energy while smelting
                    if (this.worldObj.rand.nextInt(4) == 0)
                    {
                        this.processTicks++;
                    }
                }
            }
            else
            {
                this.processTicks = 0;
            }
            
        }
    }

    /**
     * @return Is this machine able to process its specific task?
     */
    public boolean canProcess()
    {
    	if (this.waterTank.getFluidAmount() == 0)
        {
      		return false;
        }
    	if(this.containingItems[2] == null || this.containingItems[3] == null || this.containingItems[4] == null)
    	{
    		return false;
    	}
    	
    	if (this.containingItems[4] != null)
    	{
    		Block block = Block.getBlockFromItem(this.containingItems[4].getItem());
    		if(!(block instanceof ITerraformableBlock)) return false;
    	}
    	if (this.containingItems[5] != null)
    	{
    		if (this.containingItems[5].stackSize + 1 > 64)
    		{
    			return false;
    		}
    	}
	
    	return true;
    }

    /**
     * Turn one item from the furnace source stack into the appropriate smelted
     * item in the furnace result stack
     */
    public void smeltItem()
    {
        if (this.canProcess())
        {
           
            if (this.containingItems[5] == null) this.containingItems[5] = new ItemStack(Blocks.grass);
            else this.containingItems[5].stackSize++;  
            
            this.waterTank.drain(100, true);
            
            if (--this.containingItems[2].stackSize <= 0)
        	{
                this.containingItems[2] = null;
            }
        	if (--this.containingItems[3].stackSize <= 0)
        	{
                this.containingItems[3] = null;
            }
        	if (--this.containingItems[4].stackSize <= 0)
        	{
                this.containingItems[4] = null;
            }
           
        }
    }

    @Override
    public void readFromNBT(NBTTagCompound par1NBTTagCompound)
    {
        super.readFromNBT(par1NBTTagCompound);
        if (this.storage.getEnergyStoredGC() > EnergyStorageTile.STANDARD_CAPACITY)
        {
        	this.setTier2();
        	this.initialised = true;
        }
        else
        	this.initialised = false;
        this.processTicks = par1NBTTagCompound.getInteger("smeltingTicks");
        this.containingItems = this.readStandardItemsFromNBT(par1NBTTagCompound);
        
        if (par1NBTTagCompound.hasKey("waterTank"))
        {
            this.waterTank.readFromNBT(par1NBTTagCompound.getCompoundTag("waterTank"));
        }
    }

    @Override
    public void writeToNBT(NBTTagCompound par1NBTTagCompound)
    {
        if (this.tierGC == 1 && this.storage.getEnergyStoredGC() > EnergyStorageTile.STANDARD_CAPACITY)
        	this.storage.setEnergyStored(EnergyStorageTile.STANDARD_CAPACITY);
    	super.writeToNBT(par1NBTTagCompound);
        par1NBTTagCompound.setInteger("smeltingTicks", this.processTicks);
        this.writeStandardItemsToNBT(par1NBTTagCompound);
        if (this.waterTank.getFluid() != null)
        {
            par1NBTTagCompound.setTag("waterTank", this.waterTank.writeToNBT(new NBTTagCompound()));
        }
    }

